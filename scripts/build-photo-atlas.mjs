// Builds the photo atlas (src/render/photo-atlas.mjs) from the ESA/Hubble
// originals in assets-src/hubble (see ASSETS_CREDITS.md). ffmpeg crops each
// photo to its subject and shrinks it to fit a 256 px tile; the rest happens
// here, pixel by pixel:
//  - baked-in point stars are removed: a grey opening (erode, then dilate)
//    keeps everything wider than a few pixels, and only sharp peaks well above
//    it are replaced, so filaments and knots survive;
//  - alpha = brightness above the sky background, times a soft elliptical fade,
//    so even frame-filling nebulae end without a rectangle; colour is
//    un-premultiplied for the fade (the renderer premultiplies).
// The tiles are packed 4 × 3 into one 1024 × 768 image, encoded as WebP and
// embedded as a data URL, so the plugin never loads anything from the network.
// Usage: node scripts/build-photo-atlas.mjs <path to ffmpeg>
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PHOTOS } from '../src/render/photos.mjs';
const ffmpeg = process.argv[2];
if (!ffmpeg) throw Error('usage: node scripts/build-photo-atlas.mjs <ffmpeg>');
const TILE = 256, COLS = 4, ROWS = 3, AW = COLS * TILE, AH = ROWS * TILE;
const run = (args, input) => execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', ...args], { input, maxBuffer: 1 << 26 });
const lum = (px, i) => (.3 * px[i] + .59 * px[i + 1] + .11 * px[i + 2]) / 255;
// Min (erode) or max (dilate) over a (2r+1)² square, on one channel array.
function morph(src, w, h, r, pick) {
  const out = new Float32Array(src.length);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    let v = src[y * w + x];
    for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
      const xx = Math.min(w - 1, Math.max(0, x + dx)), yy = Math.min(h - 1, Math.max(0, y + dy));
      v = pick(v, src[yy * w + xx]);
    }
    out[y * w + x] = v;
  }
  return out;
}
const atlas = Buffer.alloc(AW * AH * 4);
PHOTOS.forEach((p, n) => {
  const [cx, cy, cw, ch] = p.crop, scale = Math.min(TILE / cw, TILE / ch), w = Math.round(cw * scale), h = Math.round(ch * scale);
  const px = run(['-i', fileURLToPath(new URL(`../assets-src/hubble/${p.file}`, import.meta.url)), '-vf', `crop=${cw}:${ch}:${cx}:${cy},scale=${w}:${h}:flags=lanczos`, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-']);
  // Star removal per channel: opened = dilate(erode(c)); a star is a sharp peak.
  const channels = [0, 1, 2].map(k => Float32Array.from({ length: w * h }, (_, i) => px[i * 3 + k]));
  const opened = channels.map(c => morph(morph(c, w, h, 2, Math.min), w, h, 2, Math.max));
  const ox = (n % COLS) * TILE + ((TILE - w) >> 1), oy = Math.floor(n / COLS) * TILE + ((TILE - h) >> 1);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = y * w + x, rgb = [0, 1, 2].map(k => channels[k][i]), open = [0, 1, 2].map(k => opened[k][i]);
    const peak = lum(rgb, 0) - lum(open, 0), star = Math.min(1, Math.max(0, (peak - (p.stars ?? .1)) / .08));
    const c = rgb.map((v, k) => v + (open[k] - v) * star);
    const f = Math.min(1, Math.max(0, (1 - Math.hypot((x - w / 2) / (w / 2), (y - h / 2) / (h / 2))) / (p.edge ?? .45))), fade = f * f * (3 - 2 * f);
    const a = Math.min(1, Math.max(0, (lum(c, 0) - p.floor) / p.ramp)) * fade;
    const o = ((oy + y) * AW + ox + x) * 4;
    atlas[o] = c[0]; atlas[o + 1] = c[1]; atlas[o + 2] = c[2]; atlas[o + 3] = Math.round(a * 255);
  }
});
// Encoded to a file: written to a pipe, ffmpeg cannot go back and fill in the chunk sizes.
const tmp = join(mkdtempSync(join(tmpdir(), 'atlas-')), 'atlas.webp');
run(['-f', 'rawvideo', '-pix_fmt', 'rgba', '-s', `${AW}x${AH}`, '-i', '-', '-c:v', 'libwebp', '-pix_fmt', 'yuva420p', '-q:v', '80', '-frames:v', '1', tmp], atlas);
const webp = readFileSync(tmp);
rmSync(dirname(tmp), { recursive: true, force: true });
writeFileSync(new URL('../src/render/photo-atlas.mjs', import.meta.url), `// Generated by scripts/build-photo-atlas.mjs from ESA/Hubble images (CC BY 4.0,\n// credit: ESA/Hubble & NASA; see ASSETS_CREDITS.md). Do not edit by hand.\nexport const PHOTO_ATLAS = 'data:image/webp;base64,${webp.toString('base64')}';\nexport const PHOTO_ATLAS_SIZE = Object.freeze([${AW}, ${AH}]);\nexport const PHOTO_TILE = ${TILE};\n`);
if (process.argv[3]) writeFileSync(process.argv[3], webp);
console.log(JSON.stringify({ tiles: PHOTOS.length, bytes: webp.length }));
